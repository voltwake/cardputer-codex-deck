def _compatibility_json(data: dict[str, Any]) -> str:
    output = {
        "schema": 1,
        "release": data["release"],
        "mac_app": {
            **data["mac_app"],
            "minimum_macos": "13.0",
            "architectures": ["arm64"],
        },
        "bridge_agent": data["bridge_agent"],
        "firmware": data["firmware"],
        "agent_api": data["agent_api"],
        "device_protocol": data["device_protocol"],
        "minimum_firmware": data["compatibility"]["min_firmware"],
        "legacy_protocol_1": data["compatibility"]["legacy_protocol_1"],
        "capability_profiles": data["capability_profiles"],
    }
    return json.dumps(output, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def outputs(data: dict[str, Any]) -> dict[Path, str]:
    return {
        ROOT / "bridge" / "cardbridge" / "_generated_version.py": _python(data),
        ROOT / "src" / "generated_version.h": _cpp(data),
        ROOT / "macos" / "Shared" / "GeneratedVersion.swift": _swift(data),
        ROOT / "macos" / "App" / "Info.plist": _info_plist(data),
        ROOT / "macos" / "App" / "Agent-Info.plist": _agent_info_plist(data),
        ROOT / "release" / "compatibility.json": _compatibility_json(data),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate CardBridge version constants")
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    generated = outputs(_load())
    stale: list[Path] = []
    for path, content in generated.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"stale generated file: {path}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
